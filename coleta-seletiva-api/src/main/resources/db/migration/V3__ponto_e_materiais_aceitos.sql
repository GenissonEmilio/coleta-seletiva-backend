CREATE TABLE ponto_coleta (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    logradouro VARCHAR(150) NOT NULL,
    numero VARCHAR(10),
    sem_numero BOOLEAN NOT NULL DEFAULT FALSE,
    bairro VARCHAR(80) NOT NULL,
    municipio VARCHAR(80) NOT NULL,
    uf CHAR(2) NOT NULL,
    cep CHAR(8) NOT NULL,
    complemento VARCHAR(80),
    contato VARCHAR(120),
    horarios TEXT,
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    recolhimento_domiciliar BOOLEAN NOT NULL,
    -- Valida se algum dos dois não está vazio
    CHECK ( sem_numero OR numero IS NOT NULL )
);

CREATE TABLE ponto_material (
    ponto_id BIGINT NOT NULL REFERENCES ponto_coleta(id) ON DELETE RESTRICT,
    material_id BIGINT NOT NULL REFERENCES material(id) ON DELETE RESTRICT,
    observacoes TEXT,
    limite_por_solicitacao NUMERIC(12, 3) CHECK ( limite_por_solicitacao > 0 ),
    PRIMARY KEY (ponto_id, material_id)
);