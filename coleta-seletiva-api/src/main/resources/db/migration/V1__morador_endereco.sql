
CREATE TABLE morador (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome VARCHAR(120) NOT NULL,
    email VARCHAR(160) NOT NULL UNIQUE,
    telefone VARCHAR(20),
    ativo BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE endereco (
    -- Gera a chave e permite valores manuais
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    morador_id BIGINT NOT NULL REFERENCES morador(id) ON DELETE RESTRICT,
    logradouro VARCHAR(150) NOT NULL,
    numero VARCHAR(10),
    sem_numero BOOLEAN NOT NULL DEFAULT FALSE,
    bairro VARCHAR(80) NOT NULL,
    municipio VARCHAR(80) NOT NULL,
    uf CHAR(2) NOT NULL,
    cep CHAR(8) NOT NULL,
    complemento VARCHAR(80),
    ativo BOOLEAN NOT NULL DEFAULT TRUE,
    -- Valida se algum dos dois não está vazio
    CHECK ( sem_numero OR numero IS NOT NULL )
);


