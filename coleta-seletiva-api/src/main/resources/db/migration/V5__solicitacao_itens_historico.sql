CREATE TABLE solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    protocolo VARCHAR(20) NOT NULL UNIQUE,
    morador_id BIGINT NOT NULL REFERENCES morador(id) ON DELETE RESTRICT,
    ponto_id BIGINT NOT NULL REFERENCES ponto_coleta(id) ON DELETE RESTRICT,
    endereco_id BIGINT NOT NULL REFERENCES endereco(id) ON DELETE RESTRICT,
    end_logradouro VARCHAR(150) NOT NULL,
    end_numero VARCHAR(10),
    end_sem_numero BOOLEAN NOT NULL DEFAULT FALSE,
    end_bairro VARCHAR(80) NOT NULL,
    end_municipio VARCHAR(80) NOT NULL,
    end_uf CHAR(2) NOT NULL,
    end_cep CHAR(8) NOT NULL,
    end_complemento VARCHAR(80),
    situacao VARCHAR(20) NOT NULL CHECK ( situacao IN ('SOLICITADA', 'AGENDADA', 'RECUSADA', 'CANCELADA', 'EM_RECOLHIMENTO', 'CONCLUIDA') ),
    observacoes TEXT,
    criada_em TIMESTAMPTZ NOT NULL,
    agendada_para TIMESTAMPTZ,
    concluida_em TIMESTAMPTZ,
    versao BIGINT NOT NULL DEFAULT 0,
    -- Ve se algum dos dois não está vazio
    CHECK ( end_sem_numero OR end_numero IS NOT NULL )
);

CREATE TABLE item_solicitacao (
    solicitacao_id BIGINT NOT NULL REFERENCES solicitacao(id) ON DELETE RESTRICT,
    material_id BIGINT NOT NULL REFERENCES material(id) ON DELETE RESTRICT,
    unidade VARCHAR(10) NOT NULL,
    quantidade_estimada NUMERIC(12, 3) NOT NULL CHECK ( quantidade_estimada > 0 ),
    quantidade_efetiva NUMERIC(12, 3) CHECK ( quantidade_efetiva >= 0 ),
    -- Material em peça (UNIDADE) só aceita quantidade inteira
    CHECK ( unidade <> 'UNIDADE' OR ( quantidade_estimada = TRUNC(quantidade_estimada) AND ( quantidade_efetiva IS NULL OR quantidade_efetiva = TRUNC(quantidade_efetiva) ) ) ),
    PRIMARY KEY (solicitacao_id, material_id)
);

CREATE TABLE historico_solicitacao (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitacao_id BIGINT NOT NULL REFERENCES solicitacao(id) ON DELETE RESTRICT,
    situacao_anterior VARCHAR(20),
    situacao_nova VARCHAR(20) NOT NULL,
    ocorrido_em TIMESTAMPTZ NOT NULL,
    responsavel_tipo VARCHAR(10) NOT NULL CHECK ( responsavel_tipo IN ('MORADOR', 'OPERADOR', 'ADMIN') ),
    responsavel_id BIGINT,
    motivo TEXT,
    agendamento_novo TIMESTAMPTZ
);